using System.Text.RegularExpressions;
using NovaLink.Lumen.Core.Models;

namespace NovaLink.Lumen.Core;

public static class LoaderDetector
{
    public static (string Loader, string LoaderVersion, string Kernel, string Name) Detect(string id, VersionJson json, string? metaName = null, string? profileName = null)
    {
        var libs = string.Join(' ', json.Libraries.Select(l => l.Name));
        var hints = string.Join(' ', new[] { id, json.Id, json.InheritsFrom, json.Jar, json.ClientVersion, json.MainClass, metaName, libs }.Where(x => !string.IsNullOrWhiteSpace(x))).ToLowerInvariant();
        var loader = "Vanilla";
        if (Regex.IsMatch(hints, "neoforge|net\\.neoforged")) loader = "NeoForge";
        else if (Regex.IsMatch(hints, "quilt|org\\.quiltmc")) loader = "Quilt";
        else if (Regex.IsMatch(hints, "fabric|net\\.fabricmc")) loader = "Fabric";
        else if (Regex.IsMatch(hints, "optifine")) loader = "OptiFine";
        else if (Regex.IsMatch(hints, "forge|net\\.minecraftforge|cpw\\.mods")) loader = "Forge";

        var loaderVersion = "";
        string M(string pattern) { var m = Regex.Match(hints, pattern, RegexOptions.IgnoreCase); return m.Success && m.Groups.Count > 1 ? m.Groups[1].Value : ""; }
        loaderVersion = loader switch
        {
            "Fabric" => M("fabric-loader[-_ :]?(\\d+(?:\\.\\d+)*)"),
            "Quilt" => M("quilt-loader[-_ :]?(\\d+(?:\\.\\d+)*)"),
            "NeoForge" => M("neoforge[-_ :]?(\\d+(?:\\.\\d+)*)") is { Length: > 0 } n ? n : M("net\\.neoforged:neoforge:([^:\\s]+)"),
            "Forge" => ForgeVersion(hints),
            "OptiFine" => M("optifine[-_ ]?([^_\\s]+)"),
            _ => ""
        };

        var candidates = new[] { json.ClientVersion, json.InheritsFrom, json.Jar, json.Id, id }.Where(x => !string.IsNullOrWhiteSpace(x)).Select(x => x!).ToList();
        var kernel = "";
        foreach (var raw in candidates)
        {
            var text = Regex.Replace(raw, "^minecraft[-_ ]?", "", RegexOptions.IgnoreCase);
            var m = Regex.Match(text, "^(\\d+\\.\\d+(?:\\.\\d+)?)");
            if (!m.Success) m = Regex.Match(text, "(?:^|[-_])(\\d+\\.\\d+(?:\\.\\d+)?)$");
            if (m.Success) { kernel = m.Groups[1].Value; break; }
        }
        if (kernel.Length == 0) kernel = json.ClientVersion ?? json.InheritsFrom ?? json.Id ?? id;

        var generated = loader == "Vanilla" ? "Minecraft " + kernel : loader + (loaderVersion.Length > 0 ? " " + loaderVersion : "");

        // 自定义名称优先级与旧 JS 版一致：启动器内重命名 > launcher_profiles 配置名
        // > 版本 JSON 里的非通用 name > 非自动生成的版本目录名 > 加载器名称。
        var jsonName = (json.Name ?? "").Trim();
        var custom = FirstCustomName(metaName, profileName,
            IsGenericLabel(jsonName, id, kernel, loader, loaderVersion) ? "" : jsonName,
            IsAutoGeneratedId(id) ? "" : id);
        return (loader, loaderVersion, kernel, custom.Length > 0 ? custom : generated);
    }

    private static string FirstCustomName(params string?[] candidates)
    {
        foreach (var candidate in candidates)
            if (!string.IsNullOrWhiteSpace(candidate)) return candidate.Trim();
        return "";
    }

    private static bool IsGenericLabel(string value, string id, string kernel, string loader, string loaderVersion)
    {
        if (string.IsNullOrWhiteSpace(value)) return true;
        var text = value.Trim();
        if (text.Equals(id, StringComparison.OrdinalIgnoreCase)
            || text.Equals(kernel, StringComparison.OrdinalIgnoreCase)
            || text.Equals("Minecraft", StringComparison.OrdinalIgnoreCase)
            || text.Equals("Minecraft " + kernel, StringComparison.OrdinalIgnoreCase))
            return true;
        if (loader != "Vanilla" && Regex.IsMatch(text, "^" + Regex.Escape(loader) + "([-_ ]|$)", RegexOptions.IgnoreCase))
            return true;
        if (Regex.IsMatch(text, "^(fabric-loader|quilt-loader|forge|neoforge|optifine)([-_ ]|$)", RegexOptions.IgnoreCase))
            return true;
        if (loaderVersion.Length > 0 && Regex.IsMatch(text, "^\\d+(?:\\.\\d+)+$"))
            return true;
        return false;
    }

    private static bool IsAutoGeneratedId(string id)
    {
        if (string.IsNullOrWhiteSpace(id)) return true;
        return Regex.IsMatch(id,
            "^(?:(?:fabric-loader|quilt-loader|forge|neoforge|optifine)(?:[-_]|$)|(?:\\d+\\.\\d+(?:\\.\\d+)?)(?:$|[-_](?:forge|neoforge|fabric-loader|quilt-loader|optifine)(?:[-_]|$)))",
            RegexOptions.IgnoreCase);
    }

    private static string ForgeVersion(string hints)
    {
        var m = Regex.Match(hints, "(?:^|[-_ ])1\\.\\d+(?:\\.\\d+)?-forge-(\\d+\\.\\d+(?:\\.\\d+)?)", RegexOptions.IgnoreCase);
        if (m.Success) return m.Groups[1].Value;
        m = Regex.Match(hints, "net\\.minecraftforge:forge:([^:\\s]+)", RegexOptions.IgnoreCase);
        if (!m.Success) return "";
        var v = m.Groups[1].Value;
        return v.Contains('-') ? v.Split('-').Last() : v;
    }
}
